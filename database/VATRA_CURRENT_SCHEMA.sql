CREATE OR REPLACE FUNCTION public.vatra_chat_sync_inboxes()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare
  chat_id text;
  chat_root jsonb;
  members jsonb;
  message jsonb;
  previous_messages jsonb := '{}'::jsonb;
  item record;
  participant text;
  other_participant text;
  sender text;
  stamp bigint;
  preview text;
  index_path text;
  row_value jsonb;
begin
  if new.path ~ '^chats/[^/]+/messages/[^/]+$' then
    chat_id := split_part(new.path,'/',2);
    message := new.value;
    select c.value into chat_root from public.app_data c where c.path='chats/'||chat_id;
  elsif new.path ~ '^chats/[^/]+$' then
    chat_id := split_part(new.path,'/',2);
    chat_root := new.value;
    if jsonb_typeof(new.value -> 'messages') <> 'object' then return new; end if;
    if tg_op='UPDATE' and jsonb_typeof(old.value->'messages')='object' then
      previous_messages := old.value->'messages';
    end if;
    -- Sync only newly added messages to avoid notifications for metadata edits.
    for item in select key, value from jsonb_each(new.value->'messages')
                where not(previous_messages ? key)
                order by coalesce((value->>'createdAt')::bigint,0) desc limit 1
    loop
      message := item.value;
    end loop;
  else
    return new;
  end if;

  if message is null or jsonb_typeof(message)<>'object' then return new; end if;
  members := chat_root->'members';
  sender := message->>'senderUid';
  if sender is null or jsonb_typeof(members)<>'object'
     or not(members ? sender) then return new; end if;
  stamp := coalesce(nullif(message->>'createdAt','')::bigint,
                    floor(extract(epoch from clock_timestamp())*1000)::bigint);
  preview := case when message ? 'encrypted' then 'Повідомлення'
             else left(coalesce(message->>'text','Повідомлення'),120) end;
  for participant in select jsonb_object_keys(members) loop
    -- Preserve the original chat's otherUid for both sender and recipient.
    if participant !~ '^[0-9a-fA-F-]{36}$' then continue; end if;
    select member_uid into other_participant
      from jsonb_object_keys(members) as others(member_uid)
      where member_uid <> participant limit 1;
    if other_participant is null then continue; end if;
    index_path := 'userChats/'||participant||'/'||chat_id;
    row_value := jsonb_build_object(
      'otherUid',other_participant,'updatedAt',stamp,
      'lastMessage',jsonb_build_object('text',preview,'senderUid',sender,'createdAt',stamp)
    );
    insert into public.app_data(path,value,updated_at)
    values(index_path,row_value,clock_timestamp())
    on conflict (path) do update
      set value=coalesce(public.app_data.value,'{}'::jsonb)||excluded.value,
          updated_at=clock_timestamp()
      where coalesce(nullif(public.app_data.value->'lastMessage'->>'createdAt','')::bigint,0)<=stamp;
  end loop;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.vatra_check_public_handle()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  next_handle text;
  previous_handle text;
  handle_changed boolean;
begin
  if new.path ~ '^(publicProfiles|users)/[^/]+$' then
    next_handle := new.value ->> 'handle';
    if tg_op = 'INSERT' then
      handle_changed := true;
    else
      previous_handle := case
        when old.path = new.path then old.value ->> 'handle'
        else null
      end;
      handle_changed := (next_handle is distinct from previous_handle);
    end if;

    if handle_changed and (new.path ~ '^publicProfiles/[^/]+$' or next_handle is not null) then
      if next_handle is null or next_handle !~ '^[a-z][a-z0-9._-]{1,23}$'
         or next_handle ~ '[._-]$' then
        raise exception 'Invalid @handle: use 2-24 lowercase Latin letters a-z, digits, dots, underscores or hyphens; begin with a letter and end with a letter or digit'
          using errcode = '22023';
      end if;
    end if;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.vatra_consume_rate_limit(_uid uuid, _kind text, _max_count integer, _window_seconds integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare
  slot timestamptz;
  count_after integer;
begin
  if _uid is null or _uid is distinct from auth.uid()
     or _max_count not between 1 and 1000
     or _window_seconds not between 1 and 86400 then
    raise exception 'VATRA RATE: invalid request' using errcode='P0001';
  end if;
  -- Serialize concurrent writes from this user, including different devices.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(_uid::text || ':' || _kind, 0));
  slot := to_timestamp(floor(extract(epoch from clock_timestamp()) / _window_seconds) * _window_seconds);
  insert into public.vatra_request_buckets(account_uid,action_kind,bucket_start,request_count)
  values (_uid,_kind,slot,1)
  on conflict (account_uid,action_kind,bucket_start) do update
    set request_count=public.vatra_request_buckets.request_count+1
    where public.vatra_request_buckets.request_count < _max_count
  returning request_count into count_after;
  if count_after is null then
    raise exception 'VATRA RATE: too many requests; please try again later' using errcode='P0001';
  end if;
end;
$function$;

CREATE OR REPLACE FUNCTION public.vatra_content_rate_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare
  actor uuid := auth.uid();
  old_items jsonb;
  item_id text;
  item jsonb;
  reported_uid uuid;
begin
  if actor is null then
    raise exception 'VATRA RATE: authentication required' using errcode='P0001';
  end if;

  -- Individual user posts, and posts under a community.
  if new.path ~ '^(posts/[^/]+|groupPosts/[^/]+/[^/]+)$' then
    if tg_op = 'INSERT' then
      if coalesce(new.value->>'authorUid','') <> actor::text then
        raise exception 'VATRA RATE: invalid author' using errcode='P0001';
      end if;
      perform public.vatra_consume_rate_limit(actor,'post',10,300);
    end if;
    return new;
  end if;

  -- Individual comments. Existing comments can be edited without consuming quota.
  if new.path ~ '^comments/[^/]+/[^/]+$' then
    if tg_op = 'INSERT' then
      if coalesce(new.value->>'uid','') <> actor::text then
        raise exception 'VATRA RATE: invalid comment author' using errcode='P0001';
      end if;
      perform public.vatra_consume_rate_limit(actor,'comment',20,60);
    end if;
    return new;
  end if;

  -- Compatibility with older clients that store a whole post's comment map in one row.
  if new.path ~ '^comments/[^/]+$' then
    if jsonb_typeof(new.value) <> 'object' then return new; end if;
    old_items := case when tg_op='UPDATE' and jsonb_typeof(old.value)='object'
                     then old.value else '{}'::jsonb end;
    for item_id in select jsonb_object_keys(new.value) loop
      if not(old_items ? item_id) then
        item := new.value -> item_id;
        if coalesce(item->>'uid','') <> actor::text then
          raise exception 'VATRA RATE: invalid comment author' using errcode='P0001';
        end if;
        perform public.vatra_consume_rate_limit(actor,'comment',20,60);
      end if;
    end loop;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.vatra_data_can_read(_path text, _value jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare parts text[]; uid uuid; parent_value jsonb;
begin
  uid := auth.uid();
  parts := string_to_array(_path, '/');

  -- E2EE public identity keys may only be read by signed-in users.
  -- The private key never leaves IndexedDB on the user's device.
  if _path ~ '^e2eeKeys/[^/]+$' then
    return uid is not null;
  end if;
  if _path ~ '^publicProfiles/[^/]+$' then
    return (_value ->> 'profileVisibility' is distinct from 'private')
      or (uid is not null and (parts[2] = uid::text or public.vatra_data_is_friend(parts[2], uid)));
  end if;
  if _path ~ '^friendProfiles/[^/]+$' then
    return uid is not null and (parts[2] = uid::text or public.vatra_data_is_friend(parts[2], uid));
  end if;
  if _path ~ '^users/[^/]+$' or _path ~ '^privateUsers/[^/]+$' then
    return uid is not null and parts[2] = uid::text;
  end if;
  if _path ~ '^posts/[^/]+$' then return public.vatra_data_can_read_post(parts[2], uid); end if;
  if _path ~ '^postLikes/[^/]+/[^/]+$' or _path ~ '^comments/[^/]+/[^/]+$' or _path ~ '^pollVotes/[^/]+/[^/]+$' or _path ~ '^postSaves/[^/]+/[^/]+$' or _path ~ '^postShares/[^/]+/[^/]+$' then return public.vatra_data_can_read_post(parts[2], uid); end if;

  -- Avatar reactions and comments follow public/friends/private profile privacy.
  if _path ~ '^avatarLikes/[^/]+/[^/]+(/[^/]+)?$'
     or _path ~ '^avatarComments/[^/]+/[^/]+(/[^/]+)?$' then
    select p.value into parent_value from public.app_data p
       where p.path = 'publicProfiles/' || parts[2];
    return uid is not null and (
      parts[2] = uid::text
      or (parent_value is not null and
         (coalesce(parent_value ->> 'profileVisibility', 'public') <> 'private'
          or public.vatra_data_is_friend(parts[2], uid)))
    );
  end if;
  if _path ~ '^groups/[^/]+$' then
    return coalesce(_value ->> 'visibility', 'public') <> 'private'
      or public.vatra_data_is_group_member(parts[2], uid);
  end if;
  if _path ~ '^groupPosts/[^/]+(/[^/]+)?$'
     or _path ~ '^groupMembers/[^/]+(/[^/]+)?$'
     or _path ~ '^groupAdmins/[^/]+(/[^/]+)?$'
     or _path ~ '^groupModerators/[^/]+(/[^/]+)?$' then
    select g.value into parent_value from public.app_data g where g.path = 'groups/' || parts[2];
    return coalesce(parent_value ->> 'visibility', 'public') <> 'private'
      or public.vatra_data_is_group_member(parts[2], uid);
  end if;
  if _path ~ '^videos/[^/]+$' or _path ~ '^groups/[^/]+$'
     or _path ~ '^groupMembers/[^/]+(/[^/]+)?$'
     or _path ~ '^groupAdmins/[^/]+(/[^/]+)?$'
      or _path ~ '^groupModerators/[^/]+(/[^/]+)?$'
     or _path ~ '^groupPosts/[^/]+(/[^/]+)?$' then return true; end if;
  if _path ~ '^friends/[^/]+$' or _path ~ '^following/[^/]+(/[^/]+)?$' then
    return uid is not null and parts[2] = uid::text;
  end if;
  if _path ~ '^friendRequests/[^/]+(/[^/]+)?$' then
    return uid is not null and (parts[2] = uid::text or (array_length(parts,1) >= 3 and parts[3] = uid::text));
  end if;
  if _path ~ '^saved/[^/]+(/[^/]+)?$'
     or _path ~ '^blockedUsers/[^/]+(/[^/]+)?$'
     or _path ~ '^userChats/[^/]+(/[^/]+)?$'
     or _path ~ '^activityReadAt/[^/]+$'
     or _path ~ '^chatReads/[^/]+(/[^/]+)?$' then
    return uid is not null and parts[2] = uid::text;
  end if;
  if _path ~ '^chatBlocks/[^/]+/[^/]+$' then return uid is not null and parts[3] = uid::text; end if;
  if _path ~ '^chats/[^/]+$' then
    return uid is not null and coalesce(_value -> 'members', '{}'::jsonb) ? uid::text;
  end if;
  if _path ~ '^chats/[^/]+/.+$' then
    select c.value into parent_value from public.app_data c where c.path = 'chats/' || parts[2];
    return uid is not null and coalesce(parent_value -> 'members', '{}'::jsonb) ? uid::text;
  end if;
  if _path ~ '^reports/[^/]+(/.*)?$' then return uid is not null and parts[2] = uid::text; end if;
  if _path ~ '^verifiedUsers/[^/]+$' then return true; end if;
  if _path ~ '^admins/[^/]+$' then return uid is not null and parts[2] = uid::text; end if;
  return false;
end;
$function$;

CREATE OR REPLACE FUNCTION public.vatra_data_can_read_post(_post_id text, _viewer_uid uuid)
 RETURNS boolean
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare post_value jsonb; author_uid text; post_visibility text; group_id text; group_post_id text; group_value jsonb;
begin
  select p.value into post_value from public.app_data p where p.path = 'posts/' || _post_id;
  -- Community posts keep the canonical path groupPosts/<group>/<post>.
  -- Their feed cards use g_<group_id>_<post_id> as stable reaction keys.
  if post_value is null and _post_id ~ '^g_[^_]+_[^_]+$' then
    group_id := substring(_post_id from '^g_([^_]+)_');
    group_post_id := substring(_post_id from '^g_[^_]+_([^_]+)$');
    select gp.value into post_value
    from public.app_data gp
    where gp.path = 'groupPosts/' || group_id || '/' || group_post_id;
    if post_value is null then return false; end if;
    select g.value into group_value
    from public.app_data g where g.path = 'groups/' || group_id;
    if group_value is null then return false; end if;
    return coalesce(group_value ->> 'visibility', 'public') <> 'private'
       or public.vatra_data_is_group_member(group_id, _viewer_uid);
  end if;
  if post_value is null then return false; end if;
  author_uid := coalesce(post_value ->> 'authorUid', '');
  post_visibility := coalesce(post_value ->> 'visibility', 'public');
  if _viewer_uid is not null and author_uid = _viewer_uid::text then return true; end if;
  if post_visibility = 'public' then return true; end if;
  if post_visibility = 'friends' and _viewer_uid is not null then
    return public.vatra_data_is_friend(author_uid, _viewer_uid);
  end if;
  return false;
end;
$function$;

CREATE OR REPLACE FUNCTION public.vatra_data_can_write(_path text, _value jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare parts text[]; uid uuid; parent_value jsonb; old_value jsonb;
begin
  uid := auth.uid();
  if uid is null then return false; end if;
  parts := string_to_array(_path, '/');


  -- Store public E2EE identity keys only; the browser retains both private keys.
  if _path ~ '^e2eeKeys/[^/]+$' then
    return parts[2] = uid::text
      and _value ->> 'v' = '1'
      and _value ->> 'curve' = 'P-256'
      and _value ->> 'fingerprint' ~ '^[a-f0-9]{64}$'
      and _value -> 'jwk' ->> 'kty' = 'EC'
      and _value -> 'jwk' ->> 'crv' = 'P-256'
      and _value -> 'jwk' ->> 'x' ~ '^[A-Za-z0-9_-]{43}$'
      and _value -> 'jwk' ->> 'y' ~ '^[A-Za-z0-9_-]{43}$'
      and _value -> 'signJwk' ->> 'kty' = 'EC'
      and _value -> 'signJwk' ->> 'crv' = 'P-256'
      and _value -> 'signJwk' ->> 'x' ~ '^[A-Za-z0-9_-]{43}$'
      and _value -> 'signJwk' ->> 'y' ~ '^[A-Za-z0-9_-]{43}$'
      and not (_value ? 'privateKey')
      and not (_value ? 'privateSignKey');
  end if;
  if _path ~ '^users/[^/]+$'
     or _path ~ '^privateUsers/[^/]+$'
     or _path ~ '^publicProfiles/[^/]+$'
     or _path ~ '^friendProfiles/[^/]+$'
     or _path ~ '^activityReadAt/[^/]+$' then
    return parts[2] = uid::text;
  end if;
  if _path ~ '^verifiedUsers/[^/]+$' then
    return exists (select 1 from public.app_data a where a.path = 'admins/' || uid::text and a.value = 'true'::jsonb);
  end if;
  if _path ~ '^posts/[^/]+$' then return _value ->> 'authorUid' = uid::text; end if;
  if _path ~ '^postLikes/[^/]+/[^/]+$' or _path ~ '^pollVotes/[^/]+/[^/]+$' or _path ~ '^postSaves/[^/]+/[^/]+$' or _path ~ '^postShares/[^/]+/[^/]+$' then return parts[3] = uid::text; end if;
  if _path ~ '^comments/[^/]+/[^/]+$' then return _value ->> 'uid' = uid::text; end if;

  -- Reactions are owned by the reacting user. Photo comments by author/owner.
  if _path ~ '^avatarLikes/[^/]+/[^/]+/[^/]+$' then
    return parts[4] = uid::text;
  end if;
  if _path ~ '^avatarComments/[^/]+/[^/]+/[^/]+$' then
    return _value ->> 'uid' = uid::text or parts[2] = uid::text;
  end if;


  -- A friend list is stored as one JSON object per account. Adding an entry
  -- to someone else's list requires their pending incoming request.
  if _path ~ '^friends/[^/]+$' then
    if parts[2] = uid::text then return true; end if;
    select f.value into old_value from public.app_data f where f.path = 'friends/' || parts[2];
    if old_value is not null and old_value ? uid::text
       and (old_value - uid::text) = (_value - uid::text) then return true; end if;
    return _value ? uid::text
      and _value ->> uid::text = 'true'
      and coalesce(old_value - uid::text, '{}'::jsonb) = (_value - uid::text)
      and exists (
        select 1 from public.app_data r
        where r.path = 'friendRequests/' || uid::text || '/' || parts[2]
          and r.value ->> 'status' = 'pending'
          and r.value ->> 'direction' = 'incoming'
      );
  end if;

  if _path ~ '^friendRequests/[^/]+(/[^/]+)?$' then
    return parts[2] = uid::text or (array_length(parts,1) >= 3 and parts[3] = uid::text);
  end if;
  if _path ~ '^saved/[^/]+(/[^/]+)?$'
     or _path ~ '^blockedUsers/[^/]+(/[^/]+)?$'
     or _path ~ '^following/[^/]+(/[^/]+)?$'
     or _path ~ '^userChats/[^/]+(/[^/]+)?$'
     or _path ~ '^chatReads/[^/]+(/[^/]+)?$' then return parts[2] = uid::text; end if;
  if _path ~ '^videos/[^/]+$' then return _value ->> 'authorUid' = uid::text; end if;
  if _path ~ '^groups/[^/]+$' then
    select a.value into old_value from public.app_data a where a.path = _path;
    if old_value is null then return _value ->> 'ownerUid' = uid::text; end if;
    return _value ->> 'ownerUid' = old_value ->> 'ownerUid'
      and (old_value ->> 'ownerUid' = uid::text
        or exists (select 1 from public.app_data a where a.path = 'groupAdmins/' || parts[2] || '/' || uid::text and a.value = 'true'::jsonb));
  end if;
  if _path ~ '^groupMembers/[^/]+(/[^/]+)?$' then
    return (array_length(parts,1) >= 3 and parts[3] = uid::text) or public.vatra_data_is_group_owner(parts[2], uid) or exists (select 1 from public.app_data a where a.path = 'groupAdmins/' || parts[2] || '/' || uid::text and a.value = 'true'::jsonb);
  end if;
  if _path ~ '^groupAdmins/[^/]+(/[^/]+)?$' or _path ~ '^groupModerators/[^/]+(/[^/]+)?$' then return public.vatra_data_is_group_owner(parts[2], uid) or exists (select 1 from public.app_data a where a.path = 'groupAdmins/' || parts[2] || '/' || uid::text and a.value = 'true'::jsonb); end if;
  if _path ~ '^groupPosts/[^/]+(/[^/]+)?$' then
    return _value ->> 'authorUid' = uid::text and public.vatra_data_is_group_member(parts[2], uid);
  end if;
  if _path ~ '^chats/[^/]+$' then return coalesce(_value -> 'members', '{}'::jsonb) ? uid::text; end if;
  if _path ~ '^chats/[^/]+/.+$' then
    select c.value into parent_value from public.app_data c where c.path = 'chats/' || parts[2];
    return coalesce(parent_value -> 'members', '{}'::jsonb) ? uid::text;
  end if;
  if _path ~ '^chatBlocks/[^/]+/[^/]+$' then return parts[3] = uid::text; end if;
  if _path ~ '^reports/[^/]+(/.*)?$' then return parts[2] = uid::text; end if;
  return false;
end;
$function$;

