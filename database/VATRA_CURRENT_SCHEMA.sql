CREATE OR REPLACE FUNCTION public.vatra_submit_verification(_kind text, _target text, _explanation text, _url text DEFAULT NULL::text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare target_uid uuid; new_id bigint; target_group jsonb;
