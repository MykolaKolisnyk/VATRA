CREATE OR REPLACE FUNCTION public.vatra_public_ban_status(_kind text, _target text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare target_uid uuid; ban_reason text; until_at timestamptz; since_at timestamptz;
        ban_active boolean; entitled boolean:=false; gid jsonb; deletion_at timestamptz; tombstone_at timestamptz;
begin
 if _kind='account' then
  if coalesce(_target,'') !~ '^[0-9a-fA-F-]{36}$' then return jsonb_build_object('blocked',false); end if;
  target_uid:=_target::uuid;
  select active and (expires_at is null or expires_at>now()),reason,expires_at,updated_at
   into ban_active,ban_reason,until_at,since_at
   from public.vatra_moderation_account_bans where user_id=target_uid;
  entitled := auth.uid()=target_uid;
  select deleted_at into tombstone_at from public.vatra_account_tombstones where user_id=target_uid;
  if to_regclass('public.vatra_account_lifecycle') is not null then
    execute 'select delete_after from public.vatra_account_lifecycle where user_id=$1' into deletion_at using target_uid;
  end if;
 elsif _kind='community' then
  if coalesce(_target,'') !~ '^[a-zA-Z0-9_-]{1,128}$' then return jsonb_build_object('blocked',false); end if;
  select active and (expires_at is null or expires_at>now()),reason,expires_at,updated_at
   into ban_active,ban_reason,until_at,since_at
   from public.vatra_moderation_group_bans where group_id=_target;
  select value into gid from public.app_data where path='groups/'||_target;
  entitled := auth.uid() is not null and coalesce(gid->>'ownerUid','')=auth.uid()::text;
 else return jsonb_build_object('blocked',false);
 end if;
 if coalesce(ban_active,false)=false then
  if _kind='account' and (tombstone_at is not null or deletion_at is not null) then
   return jsonb_build_object('blocked',false,'deleted',true,'pending',tombstone_at is null,
     'deleteAfter',case when entitled then deletion_at else null end,
     'sinceAt',case when entitled then deletion_at-interval '30 days' else null end,
     'canSeeDetails',entitled);
  end if;
  return jsonb_build_object('blocked',false);
 end if;
 return jsonb_build_object('blocked',true,'kind',_kind,'target',_target,
 'reason',case when entitled then ban_reason else null end,
 'expiresAt',case when entitled then until_at else null end,
 'sinceAt',case when entitled then since_at else null end,
 'permanent',case when entitled then until_at is null else null end,
 'canSeeDetails',entitled);
end $function$;

CREATE OR REPLACE FUNCTION public.vatra_publish_due_posts(max_posts integer DEFAULT 100)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare job public.vatra_scheduled_posts%rowtype;
        published integer:=0;
        destination text; now_ms bigint; record_value jsonb;
        can_publish boolean;
begin
 for job in select * from public.vatra_scheduled_posts
     where scheduled_at<=now() and published_at is null and cancelled_at is null
     order by scheduled_at
     for update skip locked
     limit least(greatest(max_posts,1),100)
 loop
  begin
   can_publish := exists (select 1 from auth.users u where u.id=job.author_uid);
   if job.group_id is not null then
     can_publish := can_publish and public.vatra_data_is_group_member(job.group_id,job.author_uid);
     if coalesce(job.payload->>'authorType','user')='group' then
      can_publish := can_publish and (
       public.vatra_data_is_group_owner(job.group_id,job.author_uid)
       or exists (select 1 from public.app_data a
                  where a.path='groupAdmins/'||job.group_id||'/'||job.author_uid::text
                    and a.value='true'::jsonb)
      );
     end if;
   end if;
   if can_publish and job.group_id is not null
      and exists (select 1 from public.app_data g where g.path='groups/'||job.group_id
        and coalesce((g.value->>'membersCanPost')::boolean,true)=false)
      and not (
        public.vatra_data_is_group_owner(job.group_id,job.author_uid)
        or exists (select 1 from public.app_data a where a.path='groupAdmins/'||job.group_id||'/'||job.author_uid::text and a.value='true'::jsonb)
      )
   then can_publish:=false; end if;
   if not can_publish then
    update public.vatra_scheduled_posts set cancelled_at=now(),
      last_error='Права на публікацію втрачено.'
    where id=job.id;
    continue;
   end if;
   destination:=case when job.group_id is null then 'posts/' else 'groupPosts/'||job.group_id||'/' end||replace(job.id::text,'-','');
   now_ms:=floor(extract(epoch from clock_timestamp())*1000)::bigint;
   record_value:=(job.payload
     - 'createdAt' - 'updatedAt')
     || jsonb_build_object('createdAt',now_ms,'updatedAt',now_ms,
                           'authorUid',job.author_uid::text);
   if job.group_id is null then
     record_value:=record_value - 'groupId' - 'authorType';
   else
     record_value:=record_value||jsonb_build_object('groupId',job.group_id);
   end if;
   insert into public.app_data(path,value,updated_at)
   values(destination,record_value,clock_timestamp())
   on conflict(path) do nothing;
   update public.vatra_scheduled_posts set published_at=clock_timestamp(),
     published_path=destination,last_error=null
   where id=job.id;
   published:=published+1;
  exception when others then
   update public.vatra_scheduled_posts set last_error=left(SQLERRM,250) where id=job.id;
  end;
 end loop;
 return published;
end;
$function$;

CREATE OR REPLACE FUNCTION public.vatra_purge_user_data(target_uid uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
 SET row_security TO 'off'
AS $function$
declare
  uid text := target_uid::text;
begin
  if exists (
    select 1 from public.app_data
    where path like 'groups/%' and value ->> 'ownerUid' = uid
  ) then raise exception 'Transfer ownership of communities before deletion'; end if;

  insert into public.vatra_account_tombstones(user_id,deleted_at) values(target_uid,now())
  on conflict (user_id) do update set deleted_at=excluded.deleted_at;

  -- Remove the user's content, including posts/comments inside other spaces.
  delete from public.app_data
  where (
    path ~ '^(posts|groupPosts)/'
    and value ->> 'authorUid' = uid
  ) or (
    path ~ '^(comments|avatarComments)/'
    and coalesce(value ->> 'uid', value ->> 'authorUid') = uid
  ) or (
    path ~ '^chats/[^/]+/messages/'
    and value ->> 'senderUid' = uid
  ) or (
    path ~ '^videos/'
    and coalesce(value ->> 'authorUid', value ->> 'uid') = uid
  ) or (
    path ~ '^reports/'
    and (value ->> 'reporterUid' = uid or path like 'reports/' || uid || '/%')
  ) or (
    path ~ '^groupContacts/'
    and value ->> 'uid' = uid
  );

  -- Remove rows directly scoped to the account and per-user reaction / membership keys.
  delete from public.app_data where
    path = any (array[
     'users/'||uid,'publicProfiles/'||uid,'friendProfiles/'||uid,
     'privateUsers/'||uid,'friends/'||uid,'following/'||uid,
     'saved/'||uid,'blockedUsers/'||uid,'userChats/'||uid,
     'friendRequests/'||uid,'chatReads/'||uid,'admins/'||uid,
     'verifiedUsers/'||uid,'e2eeKeys/'||uid,'avatarLikes/'||uid
    ]) or
    path like any (array[
     'privateUsers/'||uid||'/%','userChats/'||uid||'/%',
     'friendRequests/'||uid||'/%','saved/'||uid||'/%',
     'following/'||uid||'/%','blockedUsers/'||uid||'/%',
     'reports/'||uid||'/%','chatReads/'||uid||'/%',
     'groupMembers/%/'||uid,'groupAdmins/%/'||uid,'groupModerators/%/'||uid,
     'postLikes/%/'||uid,'postSaves/%/'||uid,'postShares/%/'||uid,
     'pollVotes/%/'||uid,'avatarLikes/%/'||uid,
     'friends/%/'||uid
    ]);

  -- Scrub cross-references in old Firebase-style objects and public contact lists.
  update public.app_data
    set value = value - uid,updated_at=now()
  where path ~ '^(friends|following|blockedUsers|groupMembers|groupAdmins|groupModerators)/'
    and jsonb_typeof(value) = 'object' and value ? uid;

  update public.app_data a
  set value = jsonb_set(a.value,'{contacts}',
    coalesce((
      select jsonb_agg(item)
      from jsonb_array_elements(case when jsonb_typeof(a.value->'contacts')='array' then a.value->'contacts' else '[]'::jsonb end) item
      where item->>'uid' is distinct from uid
    ),'[]'::jsonb),true),updated_at=now()
  where a.path like 'groups/%'
    and jsonb_typeof(a.value->'contacts') = 'array'
    and exists (
      select 1 from jsonb_array_elements(case when jsonb_typeof(a.value->'contacts')='array' then a.value->'contacts' else '[]'::jsonb end) item
      where item->>'uid' = uid
    );
end;
