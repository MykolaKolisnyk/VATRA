create or replace function public.vatra_moderation_is_admin()
returns boolean language sql stable security definer
set search_path='' set row_security=off as $admin$
 select auth.uid() is not null and exists
   (select 1 from public.vatra_verification_admins x where x.user_id=auth.uid());
$admin$;
revoke all on function public.vatra_moderation_is_admin() from public,anon;
grant execute on function public.vatra_moderation_is_admin() to authenticated;

