-- Duplicate reports are de-duplicated by their original unique app_data path.
-- Trigger derives trusted reporter UID from the path; the user cannot write into the moderation table.
create or replace function public.vatra_moderation_queue_report()
returns trigger language plpgsql security definer
set search_path='' set row_security=off as $queue$
declare r text[]; report_uid uuid; report_type text; report_target text;
begin
 if new.path !~ '^reports/[0-9a-fA-F-]{36}/[^/]+/[^/]+$' then return new; end if;
 r:=string_to_array(new.path,'/');
 if r[3] not in ('profile','post','comment','group','groupPost','video') then return new; end if;
 report_uid:=r[2]::uuid;report_type:=r[3];report_target:=r[4];
 insert into public.vatra_moderation_cases
   (report_path,reporter_uid,target_type,target_id,reason,details,created_at)
 values (new.path,report_uid,report_type,report_target,
         left(coalesce(new.value->>'reason','other'),60),
         left(coalesce(new.value->>'details',''),500),
         coalesce(to_timestamp(nullif(new.value->>'createdAt','')::numeric / 1000.0),now()))
 on conflict (report_path) do nothing;
 return new;
exception when invalid_text_representation or numeric_value_out_of_range then
 -- Broken legacy timestamps do not prevent the original report from being saved.
 insert into public.vatra_moderation_cases(report_path,reporter_uid,target_type,target_id,reason,details)
 values (new.path,report_uid,report_type,report_target,
   left(coalesce(new.value->>'reason','other'),60),
   left(coalesce(new.value->>'details',''),500))
 on conflict (report_path) do nothing;
 return new;
end $queue$;
drop trigger if exists vatra_mod_enqueue_report on public.app_data;
create trigger vatra_mod_enqueue_report
after insert on public.app_data for each row
execute function public.vatra_moderation_queue_report();

-- Import reports that users sent BEFORE enabling this queue.
insert into public.vatra_moderation_cases(report_path,reporter_uid,target_type,target_id,reason,details,created_at)
select p.path,split_part(p.path,'/',2)::uuid,split_part(p.path,'/',3),
       split_part(p.path,'/',4),
       left(coalesce(p.value->>'reason','other'),60),
       left(coalesce(p.value->>'details',''),500),
       now()
from public.app_data p
where p.path ~ '^reports/[0-9a-fA-F-]{36}/(profile|post|comment|group|groupPost|video)/[^/]+$'
on conflict (report_path) do nothing;

-- Users cannot get around a suspension by bypassing the website and using REST.
create or replace function public.vatra_moderation_account_blocked(_user uuid)
returns boolean language sql stable security definer
set search_path='' set row_security=off as $blocked$
 select _user is not null and exists(
   select 1 from public.vatra_moderation_account_bans b
   where b.user_id=_user and b.active
     and (b.expires_at is null or b.expires_at>now()));
$blocked$;
create or replace function public.vatra_moderation_group_blocked(_group text)
returns boolean language sql stable security definer
set search_path='' set row_security=off as $blocked$
 select coalesce(_group,'')<>'' and exists(
   select 1 from public.vatra_moderation_group_bans b
   where b.group_id=_group and b.active
     and (b.expires_at is null or b.expires_at>now()));
$blocked$;
grant execute on function public.vatra_moderation_account_blocked(uuid) to anon,authenticated;
grant execute on function public.vatra_moderation_group_blocked(text) to anon,authenticated;

